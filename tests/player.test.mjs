import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { prepareGameDocument, directPlayURL, validGameBuild, createTransientCaches, createTransientStorage, installSandboxStorage } from '../src/player/core.mjs';

const build = 'https://gn-math.dev/s/encoded-token/719-fix2.html';
assert.equal(validGameBuild(build), true);
for (const url of ['javascript:alert(1)', 'https://evil.test/s/x/719.html', 'http://gn-math.dev/s/x/719.html', 'https://gn-math.dev/?id=719']) assert.equal(validGameBuild(url), false);

// Regression: original pinned builds preserve their CDN base, without allowing arbitrary sources.
const pinnedDoom = 'https://raw.githubusercontent.com/gn-math/html/a64911a67f5d995a6500c5d07795cd3e506739c3/203-fix2.html';
const pinnedResident = 'https://raw.githubusercontent.com/gn-math/html/48c0631289237dd2e9e202fde532edfae4ed2acf/741-fix3.html';
assert.equal(validGameBuild(pinnedDoom), true);
assert.equal(validGameBuild(pinnedResident), true);
for (const source of [pinnedDoom.replace('gn-math/html','other/html'), pinnedDoom.replace('a64911a67f5d995a6500c5d07795cd3e506739c3','main'), pinnedDoom+'?download=1', pinnedDoom.replace('203-fix2','741-fix3'), pinnedResident.replace('https://','https://user@'), pinnedResident.replace('githubusercontent.com/','githubusercontent.com:444/')]) assert.equal(validGameBuild(source),false);
const cleanDoom = await fs.readFile('tests/fixtures/doom.html','utf8');
const preparedDoom = prepareGameDocument(cleanDoom, pinnedDoom);
assert.match(preparedDoom,/installDoomTransientFS/);
assert.match(prepareGameDocument(cleanDoom,pinnedDoom.replace('raw.githubusercontent.com','RAW.githubusercontent.com')),/installDoomTransientFS/);
assert.ok(preparedDoom.indexOf('browserfs.min.js') < preparedDoom.indexOf('installDoomTransientFS'));
assert.ok(preparedDoom.indexOf('installDoomTransientFS') < preparedDoom.indexOf('src="js/loader.js"'));
assert.match(preparedDoom, /<base href="https:\/\/cdn\.jsdelivr\.net\/gh\/bubbls\/dosbox\/">/);
assert.equal(new URL('js/dosbox-sync.js', preparedDoom.match(/<base href="([^"]+)"/)[1]).href, 'https://cdn.jsdelivr.net/gh/bubbls/dosbox/js/dosbox-sync.js');
assert.match(preparedDoom,/base-uri[^"]*https:\/\/cdn\.jsdelivr\.net/);
assert.match(preparedDoom,/script-src[^;]+https:\/\/code\.jquery\.com/);
for (const unsafe of ['https://evil.test/assets/', 'javascript:alert(1)', 'https://user:pass@cdn.jsdelivr.net/assets/', 'https://cdn.jsdelivr.net:444/assets/', 'https://cdn.jsdelivr.net.evil.test/assets/']) assert.throws(()=>prepareGameDocument('<html><base href="'+unsafe+'"><canvas></canvas></html>',pinnedDoom));
const preparedResident = prepareGameDocument(await fs.readFile('tests/fixtures/resident-evil.html','utf8'),pinnedResident);
assert.match(preparedResident, /<base href="https:\/\/raw\.githubusercontent\.com\/gn-math\/html\/48c0631289237dd2e9e202fde532edfae4ed2acf\/">/);
assert.match(preparedResident,/frame-src 'none'/);

const fixture = '<!doctype html><script>boot()</script><html><head><base href="/s/assets/"></head><body><canvas></canvas></body></html>';
const prepared = prepareGameDocument(fixture, build);
assert.match(prepared, /<base href="https:\/\/gn-math\.dev\/s\/assets\/">/);
assert.equal((prepared.match(/<base /g) || []).length, 1);
assert.ok(prepared.indexOf('Content-Security-Policy') < prepared.indexOf('boot()'));
assert.match(prepared, /frame-src 'none'/);
assert.match(prepared, /form-action 'none'/);
assert.ok(!prepared.includes('allow-same-origin'));
assert.ok(!prepared.includes('bellnewyork.org'));
assert.match(prepareGameDocument('<html><body>Game</body></html>', build), /https:\/\/gn-math\.dev\/s\/encoded-token\//);
assert.throws(() => prepareGameDocument(fixture, 'https://evil.test/game.html'));
assert.equal(directPlayURL({id:'gn-719', buildURL:build, url:'https://gn-math.dev/?id=719'}, 'http://127.0.0.1:55075/#catalogo'), 'http://127.0.0.1:55075/?play=gn-719');
assert.equal(directPlayURL({id:'gn-719', buildURL:build, url:'https://gn-math.dev/?id=719'}, 'file:///C:/Edy/catalogo.html#catalogo'), 'file:///C:/Edy/catalogo.html?play=gn-719');
assert.equal(directPlayURL({id:'other',url:'https://example.org/game'}, 'http://localhost/'), 'https://example.org/game');
assert.equal(directPlayURL({id:'gn-evil',buildURL:'https://evil.test/game',url:'https://gn-math.dev/'}, 'http://localhost/'), 'https://gn-math.dev/');
const storage = createTransientStorage();
assert.equal(storage.getItem('save'), null);
storage.setItem('save', 123);
assert.equal(storage.getItem('save'), '123');
assert.equal(storage.length, 1);
storage.clear();
assert.equal(storage.length, 0);
const caches = createTransientCaches(async () => new Response('asset'));
const cache = await caches.open('unity');
await cache.put('data', new Response('game-data'));
assert.equal(await (await cache.match('data')).text(), 'game-data');
assert.equal(await (await cache.match('data')).text(), 'game-data');
assert.equal(await cache.match('missing'), undefined);
await cache.add('loader');
assert.equal(await (await caches.match('loader')).text(), 'asset');
assert.equal(await caches.delete('unity'), true);
assert.equal(await caches.has('unity'), false);
assert.ok(prepared.indexOf('installSandboxStorage') < prepared.indexOf('boot()'));
const blocked = {};
for (const name of ['localStorage', 'sessionStorage', 'caches']) Object.defineProperty(blocked, name, {get(){throw Error('opaque context');}, configurable:true});
installSandboxStorage(blocked);
blocked.localStorage.setItem('save','session-only');
assert.equal(blocked.localStorage.getItem('save'), 'session-only');
assert.ok(await blocked.caches.open('game'));
const unavailable = {};
installSandboxStorage(unavailable);
assert.ok(await unavailable.caches.open('game'));
const catalog = JSON.parse(await fs.readFile('data/catalog.json','utf8'));
const localIDs = new Set();
for (const game of catalog.games.filter(game=>game.id.startsWith('gn-'))) {
  assert.equal(validGameBuild(game.buildURL), true, game.id);
  const url = new URL(directPlayURL(game,'file:///C:/Edy/catalogo.html#catalogo'));
  assert.equal(url.protocol,'file:');
  assert.equal(url.searchParams.get('play'),game.id);
  localIDs.add(url.href);
}
assert.equal(localIDs.size,776);
const playerMarkup = await fs.readFile('src/player/ui.html','utf8');
const sandbox = playerMarkup.match(/sandbox="([^"]+)"/);
assert.ok(sandbox, 'player iframe must have sandbox');
assert.deepEqual(sandbox[1].split(/\s+/).sort(),['allow-pointer-lock','allow-scripts']);
console.log('Direct-player boundary and portable links: passed');
